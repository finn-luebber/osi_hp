/**
 * Writes /admin/index.html and /admin/config.yml of the editing interface.
 *
 * Which Git host the editor logs in to is worked out from where the build runs:
 *   - on GitHub Actions: GitHub, this repository, login through DECAP_OAUTH_URL
 *   - on GitLab CI:      this GitLab, this project, login with DECAP_GITLAB_APP_ID
 *   - on your computer:  edits the files in this folder (start "npm run cms")
 * Every value can be set by hand with the CMS_* variables listed in docs/HOSTING.md.
 */
import fs from 'node:fs';
import path from 'node:path';

const env = process.env;
const pick = (...values) => values.find((v) => v !== undefined && v !== null && String(v).trim() !== '');
const q = (v) => JSON.stringify(String(v));   // a safe YAML string
const origin = (url) => { try { return new URL(url).origin; } catch { return ''; } };

export function cmsBackend() {
  const ci = env.GITHUB_ACTIONS === 'true' ? 'github' : env.GITLAB_CI === 'true' ? 'gitlab' : '';
  const name = pick(env.CMS_BACKEND, ci, 'local');
  if (name === 'github') {
    const base = pick(env.CMS_BASE_URL, env.DECAP_OAUTH_URL, '');
    return {
      name, local: false,
      repo: pick(env.CMS_REPO, env.GITHUB_REPOSITORY, 'OWNER/REPOSITORY'),
      branch: pick(env.CMS_BRANCH, env.GITHUB_REF_NAME, 'main'),
      yaml: (r, b) => [`name: github`, `repo: ${q(r)}`, `branch: ${q(b)}`, ...(base ? [`base_url: ${q(base)}`, `auth_endpoint: auth`] : [])],
      hosts: ['https://api.github.com', 'https://github.com', 'https://avatars.githubusercontent.com', 'https://raw.githubusercontent.com', origin(base)].filter(Boolean),
      missing: base ? '' : 'DECAP_OAUTH_URL (address of the GitHub login service)',
    };
  }
  if (name === 'gitlab') {
    const server = pick(env.CMS_BASE_URL, env.CI_SERVER_URL, 'https://gitlab.com');
    const api = pick(env.CMS_API_ROOT, env.CI_API_V4_URL, `${server}/api/v4`);
    const appId = pick(env.CMS_APP_ID, env.DECAP_GITLAB_APP_ID, '');
    return {
      name, local: false,
      repo: pick(env.CMS_REPO, env.CI_PROJECT_PATH, 'GROUP/PROJECT'),
      branch: pick(env.CMS_BRANCH, env.CI_DEFAULT_BRANCH, 'main'),
      yaml: (r, b) => [`name: gitlab`, `repo: ${q(r)}`, `branch: ${q(b)}`, `base_url: ${q(server)}`, `api_root: ${q(api)}`, `auth_type: pkce`, `app_id: ${q(appId || 'MISSING-APPLICATION-ID')}`],
      hosts: [origin(server), origin(api), 'https://secure.gravatar.com'].filter(Boolean),
      missing: appId ? '' : 'DECAP_GITLAB_APP_ID (application ID from GitLab)',
    };
  }
  // On your own computer: the editor works directly on the files in this folder.
  return {
    name: 'local', local: true, repo: 'local', branch: 'main',
    yaml: () => ['name: git-gateway'],          // never used: local_backend takes over
    hosts: ['http://localhost:8081'],
    missing: '',
  };
}

export function writeCmsFiles(outputDir, pathPrefix) {
  const b = cmsBackend();
  const dir = path.join(outputDir, 'admin');
  fs.mkdirSync(dir, { recursive: true });
  const siteUrl = pick(env.SITE_URL, env.CI_PAGES_URL, '');
  const lines = [
    '# Generated by the build from admin/cms.yml. Do not edit here.',
    'backend:',
    ...b.yaml(b.repo, b.branch).map((l) => `  ${l}`),
    '  commit_messages:',
    '    create: "Add {{collection}} “{{slug}}”"',
    '    update: "Update {{collection}} “{{slug}}”"',
    '    delete: "Delete {{collection}} “{{slug}}”"',
    '    uploadMedia: "Upload picture “{{path}}”"',
    '    deleteMedia: "Delete picture “{{path}}”"',
    ...(b.local ? ['local_backend: true'] : []),
    ...(siteUrl ? [`site_url: ${q(siteUrl)}`, `display_url: ${q(siteUrl)}`] : []),
    '',
  ];
  fs.writeFileSync(path.join(dir, 'config.yml'), lines.join('\n') + fs.readFileSync('admin/cms.yml', 'utf8'));

  const hosts = [...new Set(b.hosts)].join(' ');
  const csp = [
    "default-src 'self'",
    "script-src 'self' 'unsafe-eval'",           // the editor checks its settings with generated code
    "style-src 'self' 'unsafe-inline'",
    `img-src 'self' data: blob: ${hosts}`,
    "font-src 'self' data:",
    `connect-src 'self' blob: data: ${hosts}`,
    "frame-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
  const prefix = pathPrefix.endsWith('/') ? pathPrefix : `${pathPrefix}/`;
  fs.writeFileSync(path.join(dir, 'index.html'), `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<meta http-equiv="Content-Security-Policy" content="${csp}">
<title>OSI Lübeck – edit the website</title>
<link href="${prefix}admin/config.yml" type="text/yaml" rel="cms-config-url">
</head>
<body>
<!-- Decap CMS 3.17.3, served from this site. Git host: ${b.name}${b.local ? ' (files in this folder)' : `, ${b.repo}`}. -->
<script src="${prefix}admin/decap/decap-cms.js"></script>
</body>
</html>
`);
  // the same rule as a header for Apache servers (GitHub and GitLab Pages ignore this file)
  fs.writeFileSync(path.join(dir, '.htaccess'), `# Generated by the build. Rules for the editing interface on Apache servers.
<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}; frame-ancestors 'none'"
  Header always set X-Robots-Tag "noindex, nofollow"
  Header always set Cache-Control "no-store"
</IfModule>
`);
  const note = b.local ? 'editing the local files (run "npm run cms")' : `${b.name}, ${b.repo}, branch ${b.branch}`;
  console.log(`[osi] editing interface: ${note}${b.missing ? ` – still missing: ${b.missing}` : ''}`);
}
